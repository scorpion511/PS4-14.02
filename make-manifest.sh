set -e
cd "$(dirname "$0")"
OUT=cache.appcache

{
  echo "CACHE MANIFEST"
  echo "# generated by make-manifest.sh -- do not edit by hand"
  echo "# $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo
  
  # Recursively find all files, excluding this script and the output manifest
  find . -type f ! -name "$(basename "$0")" ! -name "$OUT" | while read -r f; do
    # Remove the leading "./" so the paths are clean for AppCache
    CLEAN_PATH="${f#./}"
    printf '%s #%s\n' "$CLEAN_PATH" "$(sha256sum "$CLEAN_PATH" | cut -c1-32)"
  done
  
  echo
  echo "NETWORK:"
  echo "*"
} > "$OUT"
echo "$OUT: $(grep -cE '^[^#[:space:]]+ #' "$OUT") entries, $(wc -c < "$OUT") bytes"
