#!/usr/bin/env bash
set -e
cd "$(dirname "$0")"
OUT=cache.manifest

{
  echo "CACHE MANIFEST"
  echo "# generated by make-manifest.sh -- do not edit by hand"
  echo "# $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo
  echo "CACHE:"

  # Recursively find all files, excluding hidden files, this script, and the manifest
  find . -type f ! -path '*/.*' ! -name "$(basename "$0")" ! -name "$OUT" | sort | while read -r f; do
    CLEAN_PATH="${f#./}"
    echo "# $(sha256sum "$CLEAN_PATH" | cut -c1-16)"
    echo "$CLEAN_PATH"
  done

  # Explicitly cache the query-string route used by launch.js
  echo "jb.html?log=1&afterglow=run&mode=goldhen"

  echo
  echo "NETWORK:"
  echo "*"
} > "$OUT"
echo "$OUT updated successfully."
